// Emails cannot use CSS variables, so the app's colors are copied into a plain module from the design tokens.
// Run after tokens change:  npm run digest:colors -w backend   (a test fails if the copy is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const tokensPath = path.join(here, '..', '..', 'frontend', 'design', 'tokens.json');
const outPath = path.join(here, '..', 'src', 'digest', 'emailColors.js');

export function buildEmailColors(tokens) {
  const out = { light: {}, dark: {} };
  for (const t of tokens.color.tokens) {
    out.light[t.name] = String(t.value.light).toUpperCase();
    out.dark[t.name] = String(t.value.dark).toUpperCase();
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));
  const body = JSON.stringify(buildEmailColors(tokens), null, 2);
  fs.writeFileSync(outPath, `// GENERATED by scripts/build-email-colors.mjs from frontend/design/tokens.json. Do not edit.\nexport const EMAIL_COLORS = ${body};\n`);
  console.log('Wrote', path.relative(process.cwd(), outPath));
}
