import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

function themeVars(tokens, theme) {
  const lines = [];
  for (const t of tokens.color.tokens) lines.push(`  --${t.name}: ${t.value[theme] ?? t.value};`);
  for (const t of tokens.shadow.tokens) lines.push(`  --${t.name}: ${t.value[theme] ?? t.value};`);
  return lines.join('\n');
}

export function generateTokensCss(tokens) {
  const shared = [
    ...tokens.spacing.tokens.map((t) => `  --${t.name}: ${t.value};`),
    ...tokens.radius.tokens.map((t) => `  --${t.name}: ${t.value};`),
    `  --font-sans: ${tokens.type.families.sans};`,
    `  --font-mono: ${tokens.type.families.mono};`,
  ].join('\n');

  const typeClasses = tokens.type.groups
    .flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })))
    .map((s) => {
      const decl = [
        `font-family: var(--font-${s.family})`,
        `font-size: ${s.fontSize}`,
        `line-height: ${s.lineHeight}`,
        `font-weight: ${s.fontWeight}`,
        s.letterSpacing ? `letter-spacing: ${s.letterSpacing}` : null,
        s.name === 'overline' ? 'text-transform: uppercase' : null,
      ].filter(Boolean);
      return `.rd-t-${s.name} { ${decl.join('; ')}; }`;
    })
    .join('\n');

  return `/* GENERATED by scripts/build-tokens.mjs from design/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${shared}
${themeVars(tokens, 'light')}
}

/* Follow the device unless the page says otherwise (data-theme on <html>). */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${themeVars(tokens, 'dark')}
  }
}
:root[data-theme='dark'] {
  color-scheme: dark;
${themeVars(tokens, 'dark')}
}

${typeClasses}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(fs.readFileSync(path.join(root, 'design', 'tokens.json'), 'utf8'));
  const out = path.join(root, 'src', 'styles', 'tokens.css');
  fs.writeFileSync(out, generateTokensCss(tokens));
  console.log(`tokens.css written (${tokens.color.tokens.length} colors).`);
}
